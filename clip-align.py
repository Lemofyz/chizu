# For each move, compare where she is in its last frame with where she is in the loop it returns to,
# and write the scale/offset that maps one onto the other (used to glide between them).
import json, os, sys
from PIL import Image
F = sys.argv[1]; OUT = sys.argv[2]
def box(path):
    im = Image.open(path).convert('L'); w, h = im.size; px = im.load()
    xs, ys = [], []
    for y in range(h):
        for x in range(w):
            if px[x, y] < 205: xs.append(x); ys.append(y)
    if len(xs) < 200: return None
    xs.sort(); ys.sort(); k = len(xs) // 100  # trim 1% outliers on each side
    x0, x1, y0, y1 = xs[k], xs[-1 - k], ys[k], ys[-1 - k]
    return {'cx': (x0 + x1) / 2 / w, 'cy': (y0 + y1) / 2 / h, 'h': (y1 - y0) / h, 'w': (x1 - x0) / w}
names = sorted({f.split('__')[0] for f in os.listdir(F)})
def home(n):
    pj = n.startswith('pj_')
    if 'h_' in n: return ('pj_' if pj else '') + 'h_blink'
    return 'pj_idle' if pj else 'idle'
out = {}
for n in names:
    if n in ('idle', 'pj_idle', 'h_blink', 'pj_h_blink', 'h_think', 'pj_h_think') or n.endswith('carry'): continue
    a, b = box(f'{F}/{n}__last.png'), box(f'{F}/{home(n)}__first.png')
    if not a or not b: continue
    s = max(.6, min(1.6, b['h'] / a['h']))
    out[n] = {'to': home(n), 's': round(s, 3),
              'dx': round((b['cx'] - (0.5 + (a['cx'] - 0.5) * s)) * 100, 1),
              'dy': round((b['cy'] - (0.5 + (a['cy'] - 0.5) * s)) * 100, 1)}
    print(f"{n:14s} -> {home(n):11s} scale {out[n]['s']:.2f}  move {out[n]['dx']:+.1f}% {out[n]['dy']:+.1f}%")
open(OUT, 'w').write('// Generated by align.py: how to glide from the end of each move into her loop.\nwindow.CHIZU_ALIGN = ' + json.dumps(out) + ';\n')
